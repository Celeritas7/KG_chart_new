// Optional isolated PostgreSQL check. Pass a PGlite module path; never connects to Supabase.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const modulePath = process.argv[2];
if (!modulePath) throw Error('Pass the path to @electric-sql/pglite@0.5.16/dist/index.js');
const { PGlite } = await import(pathToFileURL(modulePath).href);
const db = new PGlite();
const sql = await fs.readFile(new URL('../database/import-friends-names.sql', import.meta.url), 'utf8');
try {
  await db.exec(`
    CREATE SCHEMA auth;
    CREATE TABLE auth.users (email text);
    INSERT INTO auth.users VALUES ('learner@example.test');
    CREATE TABLE burmese_app_words (id int PRIMARY KEY, source text, english_meaning text, burmese_word text);
    INSERT INTO burmese_app_words VALUES (10, 'friends', 'Example Friend', 'နမူနာ'), (11, 'colloquial', 'Textbook name', 'နာမည်');
    CREATE TABLE kg_chart_topics (id varchar(50) PRIMARY KEY, icon varchar(50), sort_order int);
    INSERT INTO kg_chart_topics VALUES ('existing', '📚', 99);
    CREATE TABLE kg_chart_languages (code varchar(10) PRIMARY KEY);
    INSERT INTO kg_chart_languages VALUES ('my');
    CREATE TABLE kg_chart_topic_translations (topic_id varchar(50) REFERENCES kg_chart_topics(id), language_code varchar(10) REFERENCES kg_chart_languages(code), title_native text NOT NULL, question_english text, PRIMARY KEY(topic_id,language_code));
    CREATE TABLE kg_chart_settings (key text PRIMARY KEY, value jsonb NOT NULL, updated_at timestamptz DEFAULT now());
    INSERT INTO kg_chart_settings VALUES ('private_lessons', '[{"topic_id":"existing","emails":["other@example.test"]}]', now());
    CREATE TABLE kg_chart_topic_unlocks (email text CHECK(email=lower(email)), topic_id text, language_code text, PRIMARY KEY(email,topic_id,language_code));
    CREATE TABLE kg_chart_vocabulary (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), topic_id varchar(50) REFERENCES kg_chart_topics(id), english_text varchar(200) NOT NULL, image_filename varchar(200), extra_data jsonb DEFAULT '{}', sort_order int, updated_at timestamptz DEFAULT now());
    CREATE TABLE kg_chart_vocabulary_translations (vocabulary_id uuid REFERENCES kg_chart_vocabulary(id), language_code varchar(10) REFERENCES kg_chart_languages(code), native_text text NOT NULL, notes text, audio_url text, devanagari text, updated_at timestamptz DEFAULT now(), PRIMARY KEY(vocabulary_id,language_code));
    CREATE TABLE saved_progress (vocabulary_id uuid REFERENCES kg_chart_vocabulary(id), rating int);
  `);
  await assert.rejects(db.exec(sql), /existing learner/);
  await db.exec('ROLLBACK');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM kg_chart_topics')).rows[0].n, 1);
  await db.query("SELECT set_config('kg_chart.friends_learner_email','Learner@example.test',false)");
  await db.exec(sql);
  const first = (await db.query('SELECT * FROM kg_chart_vocabulary')).rows;
  assert.equal(first.length, 1, 'Only explicitly tagged friends are imported');
  assert.equal(first[0].image_filename, null, 'No missing photo downloads');
  assert.equal(first[0].extra_data.source_id, 10);
  await db.query('INSERT INTO saved_progress VALUES ($1,5)', [first[0].id]);
  await db.query("UPDATE kg_chart_vocabulary_translations SET audio_url='existing-audio',devanagari='existing-hint'");
  await db.exec(sql);
  assert.deepEqual((await db.query('SELECT id FROM kg_chart_vocabulary')).rows, [{id:first[0].id}], 'Repeat import retains the UUID');
  assert.equal((await db.query('SELECT rating FROM saved_progress')).rows[0].rating, 5);
  const settings = (await db.query("SELECT value FROM kg_chart_settings WHERE key='private_lessons'")).rows[0].value;
  assert.equal(settings.length, 2, 'Menu rules are not duplicated');
  assert.deepEqual(settings[0], {topic_id:'existing',emails:['other@example.test']});
  assert.deepEqual(settings[1].emails, ['learner@example.test']);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM kg_chart_topic_unlocks')).rows[0].n, 1);
  await db.exec("UPDATE burmese_app_words SET burmese_word='နမူနာနာမည်',english_meaning='Corrected example' WHERE id=10");
  await db.exec(sql);
  const corrected = (await db.query('SELECT v.id,v.english_text,t.native_text,t.audio_url,t.devanagari FROM kg_chart_vocabulary v JOIN kg_chart_vocabulary_translations t ON t.vocabulary_id=v.id')).rows[0];
  assert.equal(corrected.id, first[0].id);
  assert.equal(corrected.native_text, 'နမူနာနာမည်');
  assert.equal(corrected.english_text, 'Corrected example');
  assert.equal(corrected.audio_url, 'existing-audio');
  assert.equal(corrected.devanagari, 'existing-hint');
  await db.exec("INSERT INTO burmese_app_words VALUES (12,'friends','Another example','နာမည်')");
  await db.exec(sql);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM kg_chart_vocabulary')).rows[0].n, 2);
  await db.exec("INSERT INTO burmese_app_words VALUES (13,'friends','Incomplete example','')");
  await assert.rejects(db.exec(sql), /empty spelling/);
  await db.exec('ROLLBACK');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM kg_chart_vocabulary')).rows[0].n, 2, 'Invalid source leaves existing imports intact');
  console.log('PASS: source selection, one-name import, repeat import, corrections, progress preservation, menu rules, unlock, new names and failed-import rollback.');
} finally { await db.close(); }
